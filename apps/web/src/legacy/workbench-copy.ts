/** Only canonical hierarchy labels qualify; custom titles and reference identity stay unchanged. */
export function hierarchyUiLabel(
  label: string,
  kind: string,
  t: WorkbenchTranslate,
): string {
  const match =
    kind === "shot"
      ? /^Shot ([0-9]+(?:\.[0-9]+)*)$/.exec(label)
      : kind === "scene"
        ? /^Scene ([0-9]+)$/.exec(label)
        : null;
  if (!match) return label;
  return kind === "shot"
    ? t("Shot {number}", "镜头 {number}", { number: match[1]! })
    : t("Scene {number}", "场景 {number}", { number: match[1]! });
}
